function observancesOf(key, show) {
  const out = [];
  const md = key.slice(5);
  for (const [k] of DAY_KINDS) {
    if (show && show[k] === false) continue;
    const name = k === 'season' ? SEASON[key] : YEARLY[k][md];
    if (name) out.push({ name, kind: k });
  }
  return out;
}
